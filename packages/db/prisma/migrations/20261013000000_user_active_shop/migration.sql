-- WHY. A barber can own a shop AND hold a seat on someone else's team (an
-- independent barber who joins a shop). The active shop used to live only in
-- a per-browser cookie, so the choice never reached the phone app - its
-- dashboard WebView has its own cookie jar - and a barber who joined a team
