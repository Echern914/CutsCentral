-- Stored on the account, the choice follows the person to every device.
--
-- 🔴 A HINT, NEVER A GRANT. Every request re-verifies it against Shop.ownerId
-- or a ShopMember seat, exactly like the cookie, so a stale value (seat
-- removed, shop deleted) falls back to the person's own shop. That is also
-- why there is no foreign key.
--
-- Additive and nullable: every existing account reads null, which is exactly
-- today's behaviour, so there is nothing to backfill.
